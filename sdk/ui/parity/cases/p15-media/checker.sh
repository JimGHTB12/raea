#!/bin/bash
# img-downscale's fixtures, written into checker.ts as data: URLs: a 192x144 one-pixel checker (deep blue and pale
# amber) as PNG, and the same checker black and white as a lossless VP9 video (4:2:0 keeps a luma checker exact). A
# picture drawn below its size shows how it's minified: averaged (a mip level) or sampled (aliasing). Run it again
# only to change them (it needs ImageMagick and ffmpeg):
#   bash sdk/ui/parity/cases/p15-media/checker.sh
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d "${TMPDIR:-/tmp}/p15-checker.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
cd "$tmp"

magick -size 192x144 pattern:gray50 -fill '#1e40af' -opaque black -fill '#fde68a' -opaque white -strip checker.png
magick -size 192x144 pattern:gray50 -strip bw.png
ffmpeg -loglevel error -y -loop 1 -i bw.png -t 0.3 -vf fps=10,format=yuv420p -c:v libvpx-vp9 -lossless 1 checker.webm

b64() { base64 < "$1" | tr -d '\n'; }
{
  echo "// Generated by checker.sh: img-downscale's checkers as data: URLs. Don't edit; run the script."
  echo "/** 192x144, a one-pixel checker of #1e40af and #fde68a */"
  echo "export const CHECKER = \"data:image/png;base64,$(b64 checker.png)\";"
  echo "/** 0.3 s at 10 fps of a 192x144 one-pixel black and white checker (VP9, lossless) */"
  echo "export const CHECKER_VIDEO = \"data:video/webm;base64,$(b64 checker.webm)\";"
} > "$here/checker.ts"
wc -c "$here/checker.ts"
